fn paint_header(kit: &CanvasKit<'_>, input: &SearchInput, width: f32) {
    let margin = sxr(SEARCH_MARGIN);
    let bar = sxr(SEARCH_PLATE_BAR_W);
    fill_round_col(
        kit,
        margin,
        sxr(SEARCH_PLATE_TOP),
        margin + bar,
        sxr(SEARCH_PLATE_BOTTOM),
        0.0,
        COL_ACCENT_CYAN,
    );
    let x = margin + bar + sx(16);
    let max_w = (width as i32 - x - margin).max(1);
    let head_style = display_style(sf(SEARCH_HEAD_SIZE), COL_TEXT_MAIN);
    let head = ellipsize(kit, &head_style, &input.head_line(), max_w as f32);
    paint_head_run(kit, x, sxr(SEARCH_HEAD_BASE), &head, COL_TEXT_MAIN);
    let note_style = display_style(sf(SEARCH_NOTE_SIZE), COL_TEXT_SUB);
    let note = ellipsize(kit, &note_style, &input.note_line(), max_w as f32);
    text_sh_outlined(
        kit,
        &note_style,
        &note,
        x as f32,
        sxr(SEARCH_NOTE_BASE) as f32,
        COL_TEXT_SUB,
    );
}

fn paint_head_run(kit: &CanvasKit<'_>, x: i32, baseline: i32, value: &str, color: Color) {
    let size = sf(SEARCH_HEAD_SIZE);
    let cjk = display_style(size * 0.92, color);
    let latin = theme::title_style((size * 1.12).round().max(1.0) as u32, color);
    let mut cursor = x as f32;
    for character in value.chars() {
        if character == '·' || character == '・' || character == '•' {
            cursor += (size * 0.18).round();
            let d = (size * 0.12).round().max(2.0);
            let cy = baseline as f32 - (size * 0.30).round();
            kit.rrect_fill(widgets::rect(cursor, cy - d / 2.0, d, d), d / 2.0, color);
            cursor += d + (size * 0.18).round();
            continue;
        }
        let style = if character as u32 >= 0x2E80 {
            &cjk
        } else {
            &latin
        };
        let mut buffer = [0u8; 4];
        let piece = character.encode_utf8(&mut buffer);
        text_sh_outlined(kit, style, piece, cursor, baseline as f32, color);
        cursor += sketch::text_width(kit, style, piece).round();
    }
}

fn title_size(kit: &CanvasKit<'_>, input: &SearchInput) -> u32 {
    let plan = input.plan();
    let Some(first) = plan.cards.first() else {
        return 1;
    };
    let side = first.width() as i32;
    let base = (side as f64 * SEARCH_TITLE_PERMILLE as f64 / 1000.0).round() as u32;
    let floor = (side as f64 * SEARCH_TITLE_MIN_PERMILLE as f64 / 1000.0).round() as u32;
    let pad = side * SEARCH_CARD_PAD_PERMILLE / 1000;
    let avail = side - 2 * pad;
    if avail <= 0 {
        return base.max(1);
    }
    let probe = display_style(base.max(1) as f32, COL_TEXT_MAIN);
    let widest = input
        .hits
        .iter()
        .map(|hit| sketch::text_width(kit, &probe, &hit.title))
        .fold(0.0f32, f32::max);
    if widest <= avail as f32 || widest <= 0.0 {
        return base.max(1);
    }
    ((base as f32 * avail as f32 / widest * 0.97).max(floor as f32))
        .round()
        .max(1.0) as u32
}

fn paint_sections(kit: &CanvasKit<'_>, plan: &SearchPlan, width: f32) {
    let margin = sxr(SEARCH_MARGIN);
    let right = width as i32 - margin;
    let style = theme::title_style(sf(SEARCH_GROUP_SIZE).round().max(1.0) as u32, COL_TEXT_SUB);
    let rule = sxr(SEARCH_FOOT_RULE_H).max(1);
    for section in &plan.sections {
        sketch::text(
            kit,
            &style,
            &section.label,
            margin as f32,
            section.label_base as f32,
            COL_TEXT_SUB,
        );
        fill_round_col(
            kit,
            margin,
            section.rule_y,
            right,
            section.rule_y + rule,
            0.0,
            COL_SEARCH_RULE,
        );
    }
}

fn paint_grid(kit: &CanvasKit<'_>, input: &SearchInput, plan: &SearchPlan, title: u32) {
    for (index, area) in plan.cards.iter().enumerate() {
        let Some(hit) = input.hits.get(index) else {
            return;
        };
        paint_card(kit, hit, *area, title);
    }
}

fn paint_card(kit: &CanvasKit<'_>, hit: &SearchHit, area: Rect, title_size: u32) {
    let side = area.width();
    let side_px = side as i32;
    let radius = side * 0.045;
    let mut drawn = false;
    for key in hit.jacket_keys() {
        if kit.draw_asset_cover(&key, area, radius).is_ok() {
            drawn = true;
            break;
        }
    }
    if !drawn {
        kit.rrect_fill(area, radius, COL_SEARCH_PLACEHOLDER);
    }
    paint_scrim(kit, area, radius);
    let pad = side_px * SEARCH_CARD_PAD_PERMILLE / 1000;
    let avail = (side as i32 - 2 * pad).max(1);
    let base = area.top() as i32 + side_px - side_px * SEARCH_TITLE_LIFT_PERM / 1000;
    let style = display_style(title_size as f32, COL_TEXT_MAIN);
    let title = ellipsize(kit, &style, &hit.title, avail as f32);
    text_sh_outlined(
        kit,
        &style,
        &title,
        (area.left() as i32 + pad) as f32,
        base as f32,
        COL_TEXT_MAIN,
    );
    paint_levels(kit, hit, area);
}

fn paint_scrim(kit: &CanvasKit<'_>, area: Rect, radius: f32) {
    let side = area.width() as i32;
    let left = area.left() as i32;
    let top = area.top() as i32 + side - side * SEARCH_SCRIM_PERMILLE / 1000;
    let bottom = area.top() as i32 + side;
    let height = bottom - top;
    let solid = height * SEARCH_SCRIM_SOLID / 1000;
    let ramp_end = bottom - solid;
    let clear = COL_SEARCH_SCRIM.with_alpha(0);
    fill_round_gradient(
        kit,
        left,
        top,
        left + side,
        ramp_end,
        clear,
        COL_SEARCH_SCRIM,
    );
    fill_round_col(
        kit,
        left,
        ramp_end,
        left + side,
        bottom,
        radius,
        COL_SEARCH_SCRIM,
    );
}

fn diff_slot(difficulty: Difficulty) -> Option<usize> {
    match difficulty {
        Difficulty::Past => Some(0),
        Difficulty::Present => Some(1),
        Difficulty::Future => Some(2),
        Difficulty::Eternal => Some(3),
        Difficulty::Beyond => Some(4),
        Difficulty::Ins => Some(4),
    }
}

fn paint_levels(kit: &CanvasKit<'_>, hit: &SearchHit, area: Rect) {
    let side = area.width() as i32;
    let pad = side * SEARCH_CARD_PAD_PERMILLE / 1000;
    let cell_w = (side - 2 * pad) as f64 / SEARCH_DIFF_SLOTS as f64;
    let left = area.left() as i32 + pad;
    let code_size = (side as f64 * SEARCH_CELL_DIFF_PERMILLE as f64 / 1000.0)
        .round()
        .max(1.0) as u32;
    let const_size = (side as f64 * SEARCH_CELL_CONST_PERMILLE as f64 / 1000.0)
        .round()
        .max(1.0) as u32;
    let code_base = area.top() as i32 + side - side * SEARCH_CELL_DIFF_LIFT_PERM / 1000;
    let const_base = area.top() as i32 + side - side * SEARCH_CELL_CONST_LIFT_PERM / 1000;
    for chart in &hit.charts {
        let Some(slot) = diff_slot(chart.difficulty) else {
            continue;
        };
        if !chart.has_constant || chart.constant <= 0.0 {
            continue;
        }
        let lit = hit.active == Some(chart.difficulty);
        let code_ink = if lit { COL_ACCENT_CYAN } else { COL_TEXT_DIM };
        let const_ink = if lit { COL_TEXT_MAIN } else { COL_TEXT_SUB };
        let code = theme::title_style(code_size, code_ink);
        let constant = theme::title_style(const_size, const_ink);
        let code_text = chart.difficulty.as_str();
        let const_text = format!("{:.1}", chart.constant);
        let cx = left as f64 + slot as f64 * cell_w;
        let code_x = (cx
            + (cell_w - sketch::text_width(kit, &code, code_text).round() as f64) / 2.0)
            .round();
        let const_x = (cx
            + (cell_w - sketch::text_width(kit, &constant, &const_text).round() as f64) / 2.0)
            .round();
        text_sh_outlined(
            kit,
            &code,
            code_text,
            code_x as f32,
            code_base as f32,
            code_ink,
        );
        text_sh_outlined(
            kit,
            &constant,
            &const_text,
            const_x as f32,
            const_base as f32,
            const_ink,
        );
    }
}

fn paint_footer(kit: &CanvasKit<'_>, plan: &SearchPlan, width: f32) {
    let margin = sxr(SEARCH_MARGIN);
    let bottom = plan.last_bottom();
    let rule_y = bottom + sxr(SEARCH_FOOT_RULE_TOP);
    fill_round_col(
        kit,
        margin,
        rule_y,
        width as i32 - margin,
        rule_y + sxr(SEARCH_FOOT_RULE_H),
        0.0,
        COL_SEARCH_RULE,
    );
    let style = display_style(sf(SEARCH_FOOT_SIZE) * 0.94, COL_TEXT_SUB);
    paint_spaced_run(
        kit,
        &style,
        margin as f32,
        (bottom + sxr(SEARCH_FOOT_TEXT_TOP)) as f32,
        SEARCH_FOOT_MARK,
        COL_TEXT_SUB,
        sf(3.0).round(),
    );
}

fn paint_spaced_run(
    kit: &CanvasKit<'_>,
    style: &aurorix_render::TextStyle,
    x: f32,
    baseline: f32,
    value: &str,
    color: Color,
    track: f32,
) {
    let mut cursor = x;
    for character in value.chars() {
        let mut buffer = [0u8; 4];
        let piece = character.encode_utf8(&mut buffer);
        sketch::text(kit, style, piece, cursor, baseline, color);
        cursor += sketch::text_width(kit, style, piece).round() + track;
    }
}

